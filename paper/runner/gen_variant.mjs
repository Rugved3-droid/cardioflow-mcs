// Generates paper/runner/variant/: a mechanical copy of src/model/ in which a
// fixed list of module-level numeric constants becomes settable. Nothing else is
// changed. src/model/ itself is never modified.
//
// Purpose: time-step convergence (SUBSTEPS) and sensitivity of device-curve
// constants (V1, V4) need knobs the shipped code hard-codes. p0_equivalence.ts
// proves that the variant at its default knob values is bit-identical to the
// shipped model, so results obtained with it apply to the shipped model.
//
// Run: node paper/runner/gen_variant.mjs
import { mkdirSync, readFileSync, writeFileSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', '..', 'src', 'model');
const OUT = join(here, 'variant');

/** file (relative to src/model) -> constants made settable */
const KNOBS = {
  'constants.ts': ['SUBSTEPS'],
  'devices/impella.ts': ['H_MAX', 'K', 'SUCTION_START', 'SUCTION_END'],
  'devices/ecmo.ts': ['DRAIN_ZERO_MMHG', 'DRAIN_FULL_MMHG'],
  'devices/iabp.ts': ['BALLOON_VOLUME_ML', 'INFLATE_MS', 'DEFLATE_MS', 'DEFLATE_LEAD_MS'],
};

function walk(dir, rel = '') {
  const out = [];
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    const r = rel ? `${rel}/${f}` : f;
    if (statSync(p).isDirectory()) out.push(...walk(p, r));
    else out.push(r);
  }
  return out;
}

const report = [];
for (const rel of walk(SRC)) {
  const src = join(SRC, rel);
  const dst = join(OUT, rel);
  mkdirSync(dirname(dst), { recursive: true });
  if (!rel.endsWith('.ts') || !KNOBS[rel]) {
    copyFileSync(src, dst);
    continue;
  }
  let text = readFileSync(src, 'utf8');
  const names = KNOBS[rel];
  for (const n of names) {
    const re = new RegExp(`^(export )?const ${n} = `, 'm');
    if (!re.test(text)) throw new Error(`${rel}: constant ${n} not found`);
    text = text.replace(re, `export let ${n} = `);
  }
  const defaults = names.map((n) => `${n}: ${n}`).join(', ');
  text +=
    `\n// ---- generated by paper/runner/gen_variant.mjs ----\n` +
    `export const __defaults = { ${defaults} };\n` +
    `export function __set(name: string, v: number): void {\n` +
    `  switch (name) {\n` +
    names.map((n) => `    case '${n}': ${n} = v; return;\n`).join('') +
    `  }\n  throw new Error('unknown knob ' + name);\n}\n` +
    `export function __reset(): void {\n` +
    names.map((n) => `  ${n} = __defaults.${n};\n`).join('') +
    `}\n`;
  writeFileSync(dst, text);
  report.push(`${rel}: ${names.join(', ')}`);
}
writeFileSync(
  join(OUT, 'README.md'),
  '# GENERATED - do not edit\n\nMechanical copy of `src/model/` produced by `paper/runner/gen_variant.mjs`.\n' +
    'Only change: these constants are `export let` with `__set/__reset`:\n\n' +
    report.map((r) => `- ${r}`).join('\n') +
    '\n\nBit-identity to the shipped model at default knobs is proven by `paper/scripts/p0_equivalence.ts`.\n',
);
console.log('variant written:\n' + report.join('\n'));
